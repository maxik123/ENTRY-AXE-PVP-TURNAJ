// ==========================
// OPEN PROFILE
// ==========================


function openPlayer(index){


const player = players[index];


document.getElementById("modalSkin").src =
`https://mc-heads.net/body/${player.name}`;


document.getElementById("modalName").innerHTML =
player.name;


let rank =
document.getElementById("modalRank");


rank.innerHTML =
player.rank;


rank.className =
"rank " + player.rank;



document.getElementById("modalDescription").innerHTML =
player.description;



let matches =
document.getElementById("modalMatches");


matches.innerHTML="";


player.upcoming.forEach(enemy=>{


matches.innerHTML += `

<li>
 ${player.name} vs ${enemy}
</li>

`;

});





let socials =
document.getElementById("modalSocials");


socials.innerHTML="";



if(player.socials.youtube){

socials.innerHTML += `
<a href="${player.socials.youtube}" target="_blank">
 YouTube
</a>
`;

}


if(player.socials.twitch){

socials.innerHTML += `
<a href="${player.socials.twitch}" target="_blank">
 Twitch
</a>
`;

}


if(player.socials.instagram){

socials.innerHTML += `
<a href="${player.socials.instagram}" target="_blank">
 Instagram
</a>
`;

}


if(player.socials.discord){

socials.innerHTML += `
<a href="${player.socials.discord}" target="_blank">
 Discord
</a>
`;

}



document
.getElementById("playerModal")
.classList.add("show");


}





// ==========================
// CLOSE PROFILE
// ==========================


document
.getElementById("closeModal")
.onclick=function(){


document
.getElementById("playerModal")
.classList.remove("show");


};





document
.getElementById("playerModal")
.onclick=function(e){


if(e.target.id==="playerModal"){


document
.getElementById("playerModal")
.classList.remove("show");


}


};
